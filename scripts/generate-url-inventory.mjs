// Generates config/url-inventory/<site>.txt (agent-sdlc-site#18, #31).
//
// The URL inventory lists every URL that a site served: HTML pages and
// non-HTML files (favicons, robots.txt, llms.txt, JSON, Markdown). The
// redirect validator (scripts/validate-redirects.mjs) requires that each
// inventory URL is a built file or a redirect key, so no old URL breaks.
//
// Sources:
//   1. The current build in apps/site/dist/<site>/. Run `npm run build:all`
//      on the base commit before you run this script.
//   2. With --live, the live sitemap.xml of each canonical domain.
//   3. The URLs already in the inventory file. The script never removes a
//      URL: a URL that a site served once must stay covered.
//
// URL form: no trailing slash, except the site root "/". Hashed build
// assets under /_astro/ change with each build, so they are not listed.
//
// Usage: node scripts/generate-url-inventory.mjs [--live]

import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'apps/site/dist');
const outDir = join(root, 'config/url-inventory');
const SITES = ['agentsdlc', 'orbit', 'agdr'];
const HOSTS = { agentsdlc: 'https://agentsdlc.ai', orbit: 'https://orbitspec.dev', agdr: 'https://agdr.dev' };
const live = process.argv.includes('--live');

/** Built file -> URL path in the one URL form. @param {string} rel */
export function urlForFile(rel) {
  const path = `/${rel.split(sep).join('/')}`;
  if (path === '/index.html') return '/';
  if (path.endsWith('/index.html')) return path.slice(0, -'/index.html'.length);
  return path;
}

/** @param {string} dir @param {string} base @returns {string[]} */
export function builtUrls(dir, base = dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      if (full === join(base, '_astro')) continue;
      out.push(...builtUrls(full, base));
    } else out.push(urlForFile(relative(base, full)));
  }
  return out;
}

/** @param {string} file @returns {string[]} */
function readInventory(file) {
  if (!existsSync(file)) return [];
  return readFileSync(file, 'utf8').split('\n').map(line => line.trim()).filter(line => line && !line.startsWith('#'));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(outDir, { recursive: true });
  for (const site of SITES) {
    const file = join(outDir, `${site}.txt`);
    const urls = new Set(readInventory(file));
    const siteDir = join(dist, site);
    if (!existsSync(siteDir)) throw new Error(`No build output at ${relative(root, siteDir)}. Run npm run build:all first.`);
    for (const url of builtUrls(siteDir)) urls.add(url);
    if (live) {
      const response = await fetch(`${HOSTS[site]}/sitemap.xml`);
      if (!response.ok) throw new Error(`${HOSTS[site]}/sitemap.xml returned ${response.status}`);
      for (const [, loc] of (await response.text()).matchAll(/<loc>([^<]*)<\/loc>/g)) {
        const url = new URL(loc);
        if (url.origin !== HOSTS[site]) throw new Error(`${site}: live sitemap URL ${loc} is on another host`);
        let path = url.pathname;
        while (path.length > 1 && path.endsWith('/')) path = path.slice(0, -1);
        urls.add(path);
      }
    }
    const header = [
      `# URL inventory for ${HOSTS[site]} (agent-sdlc-site#18, #31).`,
      '# Every URL that this site served. Generated by scripts/generate-url-inventory.mjs',
      '# from the build of the base commit and the live sitemap. Do not remove a URL.',
      '# scripts/validate-redirects.mjs requires each URL to be a built file or a redirect key.'
    ];
    writeFileSync(file, `${header.join('\n')}\n${[...urls].sort().join('\n')}\n`);
    console.log(`${site}: ${urls.size} URLs -> ${relative(root, file)}`);
  }
}
